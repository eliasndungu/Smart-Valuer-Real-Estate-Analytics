"""
Pydantic schemas for the prediction endpoint.
"""

from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field


class PropertyType(str, Enum):
    apartment = "apartment"
    house = "house"
    land = "land"
    commercial = "commercial"
    studio = "studio"


class ListingType(str, Enum):
    sale = "sale"
    rent = "rent"


class PropertyFeatures(BaseModel):
    """Input features used by the price prediction model."""

    location: str = Field(
        ...,
        description="Neighborhood or area name, e.g. 'Kilimani' or 'Westlands'",
        examples=["Kilimani"],
    )
    size_sqft: float = Field(
        ...,
        gt=0,
        description="Total floor area in square feet",
        examples=[1200.0],
    )
    bedrooms: int = Field(
        ...,
        ge=0,
        le=20,
        description="Number of bedrooms (0 for studio)",
        examples=[3],
    )
    bathrooms: int = Field(
        1,
        ge=0,
        le=20,
        description="Number of bathrooms",
        examples=[2],
    )
    property_type: PropertyType = Field(
        PropertyType.apartment,
        description="Type of property",
        examples=["apartment"],
    )
    listing_type: ListingType = Field(
        ListingType.sale,
        description="Whether the property is for sale or rent",
        examples=["sale"],
    )
    amenities: list[str] = Field(
        default_factory=list,
        description="List of available amenities, e.g. ['parking', 'gym', 'pool']",
        examples=[["parking", "gym"]],
    )
    county: Optional[str] = Field(
        None,
        description="Kenyan county, e.g. 'Nairobi'",
        examples=["Nairobi"],
    )


class PricePredictionResponse(BaseModel):
    """Response returned by POST /predict."""

    predicted_price_kes: float = Field(
        ...,
        description="Estimated property price in Kenyan Shillings (KES)",
    )
    price_per_sqft_kes: float = Field(
        ...,
        description="Estimated price per square foot in KES",
    )
    confidence_interval: dict[str, float] = Field(
        ...,
        description="95% confidence interval: {'lower': ..., 'upper': ...}",
    )
    model_version: str = Field(
        ...,
        description="Version tag of the model used for this prediction",
    )
    disclaimer: str = Field(
        default=(
            "This is a placeholder prediction generated by a dummy model. "
            "Replace with a trained model before using in production."
        )
    )
